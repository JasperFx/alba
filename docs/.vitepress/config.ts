import { defineConfig, type HeadConfig } from 'vitepress'
import llmstxt, { copyOrDownloadAsMarkdownButtons } from 'vitepress-plugin-llms'

const siteUrl = 'https://jasperfx.github.io/alba/'
const siteDescription = 'Alba is a .NET library for fast, readable integration tests of ASP.NET Core applications. It runs HTTP requests through your app in memory with TestServer.'
const socialImage = `${siteUrl}og-image.png`

export default defineConfig({
    lang: 'en-US',
    title: 'Alba',
    titleTemplate: ':title | Alba',
    description: siteDescription,
    base: '/alba/',
    // agent-prompt.md is served as-is for agents to fetch, not rendered as a page
    srcExclude: ['public/**'],
    cleanUrls: true,
    lastUpdated: true,
    sitemap: {
        hostname: siteUrl
    },
    head: [
        ['link', { rel: 'icon', type: 'image/png', href: '/alba/favicon.png' }],
        ['meta', { name: 'theme-color', content: '#4db6ac' }],
        ['meta', { property: 'og:site_name', content: 'Alba' }],
        ['meta', { property: 'og:image', content: socialImage }],
        ['meta', { property: 'og:image:width', content: '1200' }],
        ['meta', { property: 'og:image:height', content: '630' }],
        ['meta', { property: 'og:image:alt', content: 'Alba: integration testing for ASP.NET Core' }],
        ['meta', { name: 'twitter:card', content: 'summary_large_image' }],
        ['meta', { name: 'twitter:image', content: socialImage }]
    ],
    transformHead({ pageData, title, description }) {
        const url = canonicalUrl(pageData.relativePath)
        const isHome = pageData.relativePath === 'index.md'

        const head: HeadConfig[] = [
            ['link', { rel: 'canonical', href: url }],
            ['meta', { property: 'og:type', content: isHome ? 'website' : 'article' }],
            ['meta', { property: 'og:url', content: url }],
            ['meta', { property: 'og:title', content: title }],
            ['meta', { property: 'og:description', content: description }],
            ['meta', { name: 'twitter:title', content: title }],
            ['meta', { name: 'twitter:description', content: description }],
            ['script', { type: 'application/ld+json' }, JSON.stringify(structuredData(pageData, url, description, isHome))]
        ]

        if (!isHome) {
            // Markdown copy of the page generated by vitepress-plugin-llms
            head.push(['link', { rel: 'alternate', type: 'text/markdown', href: siteUrl + pageData.relativePath }])
        }

        if (pageData.lastUpdated) {
            head.push(['meta', { property: 'article:modified_time', content: new Date(pageData.lastUpdated).toISOString() }])
        }

        return head
    },
    vite: {
        plugins: [
            llmstxt({
                domain: 'https://jasperfx.github.io',
                ignoreFiles: ['public/**', '.vitepress/**'],
                description: 'Integration testing for ASP.NET Core applications',
                details: [
                    'Alba is an open source .NET library (NuGet package `Alba`) for integration testing ASP.NET Core applications.',
                    'It runs HTTP requests through the real application in memory with ASP.NET Core\'s TestServer and asserts on',
                    'the response with a declarative *scenario* API. Alba 9 targets .NET 10 and .NET 11 and works with xUnit, NUnit and TUnit.',
                    '',
                    `- Prompt for AI coding agents adding Alba tests to a project: ${siteUrl}agent-prompt.md`,
                    '- Source code: https://github.com/JasperFx/alba',
                    '- NuGet package: https://www.nuget.org/packages/Alba'
                ].join('\n')
            })
        ],
    },
    themeConfig: {
        logo: { src: '/alba_logo.png', alt: 'Alba' },
        siteTitle: false,
        socialLinks: [
            { icon: 'github', link: 'https://github.com/JasperFx/alba' }
        ],

        editLink: {
            pattern: 'https://github.com/JasperFx/alba/edit/master/docs/:path',
            text: 'Suggest changes to this page'
        },

        nav: [
            { text: 'Docs', link: '/guide/gettingstarted' },
            { text: 'Discord | Join Chat', link: 'https://discord.gg/WMxrvegf8H' }
        ],

        search: {
            provider: 'local'
        },

        sidebar: [
            {
                text: 'Getting Started',
                collapsed: false,
                items: getGuideSidebar()
            },
            {
                text: 'Scenario Testing',
                collapsed: false,
                items: getScenarioSidebar()
            }
        ]
    },
    markdown: {
        linkify: false,
        config(md) {
            md.use(copyOrDownloadAsMarkdownButtons)
        }
    }
})

function canonicalUrl(relativePath: string) {
    return siteUrl + relativePath.replace(/(^|\/)index\.md$/, '$1').replace(/\.md$/, '')
}

function structuredData(pageData: { title: string, relativePath: string, lastUpdated?: number }, url: string, description: string, isHome: boolean) {
    const software = {
        '@type': 'SoftwareSourceCode',
        '@id': `${siteUrl}#software`,
        name: 'Alba',
        description: siteDescription,
        url: siteUrl,
        codeRepository: 'https://github.com/JasperFx/alba',
        programmingLanguage: 'C#',
        runtimePlatform: '.NET',
        license: 'https://www.apache.org/licenses/LICENSE-2.0',
        sameAs: ['https://www.nuget.org/packages/Alba']
    }

    if (isHome) {
        return {
            '@context': 'https://schema.org',
            '@graph': [
                { '@type': 'WebSite', '@id': `${siteUrl}#website`, name: 'Alba', url: siteUrl, description: siteDescription },
                software
            ]
        }
    }

    const section = pageData.relativePath.startsWith('scenarios/')
        ? { name: 'Scenario Testing', url: `${siteUrl}scenarios/writingscenarios` }
        : { name: 'Getting Started', url: `${siteUrl}guide/gettingstarted` }

    return {
        '@context': 'https://schema.org',
        '@graph': [
            {
                '@type': 'TechArticle',
                headline: pageData.title,
                description,
                url,
                ...(pageData.lastUpdated ? { dateModified: new Date(pageData.lastUpdated).toISOString() } : {}),
                isPartOf: { '@type': 'WebSite', '@id': `${siteUrl}#website`, name: 'Alba', url: siteUrl },
                about: { '@id': software['@id'] }
            },
            {
                '@type': 'BreadcrumbList',
                itemListElement: [
                    { '@type': 'ListItem', position: 1, name: 'Alba', item: siteUrl },
                    { '@type': 'ListItem', position: 2, name: section.name, item: section.url },
                    { '@type': 'ListItem', position: 3, name: pageData.title, item: url }
                ]
            }
        ]
    }
}

