using System.Text;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Routing;
using Microsoft.AspNetCore.Routing.Patterns;
using Microsoft.Extensions.DependencyInjection;

namespace Alba.Internal;

internal static class RouteNameResolver
{
    /// <summary>
    /// Generates the url for the endpoint with this route name. Lookup goes through route name
    /// metadata, which minimal API WithName(), MVC Name = and Wolverine RouteName all produce.
    /// </summary>
    public static string Resolve(IServiceProvider services, string routeName, object? routeValues)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(routeName);

        var links = services.GetService<LinkGenerator>() ?? throw new InvalidOperationException(
            $"Cannot resolve the route name '{routeName}' because the application does not use ASP.NET Core routing.");

        var values = new RouteValueDictionary(routeValues);

        return links.GetPathByRouteValues(routeName, values)
               ?? throw new InvalidOperationException(describeFailure(services, routeName, values));
    }

    /// <summary>
    /// Applies an escaped url, as generated by LinkGenerator, to the request
    /// </summary>
    public static void Apply(HttpRequest request, string url)
    {
        var queryStart = url.IndexOf('?');
        if (queryStart < 0)
        {
            request.Path = PathString.FromUriComponent(url);
            return;
        }

        request.Path = PathString.FromUriComponent(url[..queryStart]);
        request.QueryString = new QueryString(url[queryStart..]);
    }

    private static string describeFailure(IServiceProvider services, string routeName, RouteValueDictionary values)
    {
        var named = (services.GetService<EndpointDataSource>()?.Endpoints ?? [])
            .OfType<RouteEndpoint>()
            .Where(e => e.Metadata.GetMetadata<ISuppressLinkGenerationMetadata>()?.SuppressLinkGeneration != true)
            .Select(e => (Name: e.Metadata.GetMetadata<IRouteNameMetadata>()?.RouteName, Endpoint: e))
            .Where(x => !string.IsNullOrEmpty(x.Name))
            .OrderBy(x => x.Name, StringComparer.OrdinalIgnoreCase)
            .ToList();

        var matches = named.Where(x => string.Equals(x.Name, routeName, StringComparison.OrdinalIgnoreCase)).ToList();

        var writer = new StringBuilder();

        if (matches.Count == 0)
        {
            writer.AppendLine($"No endpoint has the route name '{routeName}'.");
            if (named.Count == 0)
            {
                writer.AppendLine("The application has no named routes.");
            }
            else
            {
                writer.AppendLine("Known route names:");
                foreach (var (name, endpoint) in named) writer.AppendLine($"  {name}: {describe(endpoint)}");
            }

            return writer.ToString();
        }

        writer.AppendLine($"Could not generate a url for the route name '{routeName}' from the supplied route values.");
        foreach (var (_, endpoint) in matches)
        {
            writer.AppendLine($"  Route: {describe(endpoint)}");

            var missing = endpoint.RoutePattern.Parameters
                .Where(p => !p.IsOptional && !p.IsCatchAll && !endpoint.RoutePattern.Defaults.ContainsKey(p.Name))
                .Where(p => !values.ContainsKey(p.Name))
                .Select(p => p.Name)
                .ToList();

            writer.AppendLine(missing.Count > 0
                ? $"  Missing required route values: {string.Join(", ", missing)}"
                : "  Check that the supplied values satisfy the route constraints.");
        }

        writer.AppendLine(values.Count == 0
            ? "  Supplied route values: (none)"
            : $"  Supplied route values: {string.Join(", ", values.Select(x => $"{x.Key}={x.Value}"))}");

        return writer.ToString();
    }

    private static string describe(RouteEndpoint endpoint)
    {
        var pattern = endpoint.RoutePattern.RawText ?? endpoint.DisplayName ?? "(unknown pattern)";
        var methods = endpoint.Metadata.GetMetadata<IHttpMethodMetadata>()?.HttpMethods;

        return methods is { Count: > 0 } ? $"{string.Join(", ", methods)} {pattern}" : pattern;
    }
}
